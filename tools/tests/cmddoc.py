import os,sys
base=os.path.dirname(os.path.abspath(__file__))+'/..'
out_path=sys.argv[1]
rows=[]
for line in open(base+'/commands.txt',encoding='utf-8'):
    line=line.strip()
    if not line or line.startswith('#'): continue
    rows.append([x.strip() for x in line.split('|')])
out=['# Команды админ-панели','',
'Эти команды игра понимает **сама и сразу**, без запроса к ИИ. Если в команде есть слова, которых нет в словаре, она уходит в Gemini: он понимает почти любую формулировку, но решает по правилам ниже.','',
'## Правила','',
'- **Можно всё, что есть в игре**, в полную силу: любое количество ресурсов, заморозка до 10 минут, отключение управления, переворот экрана и т.д.',
'- **Если число не указано, дают по-крупному**:',
'  - ресурсы: 30 000 дерева, 20 000 камня, 6 000 золота;',
'  - войска: 50 военных;',
'  - земли: открываются все участки и мост;',
'  - здания: прокачиваются до максимума;',
'  - армия: урон ×10;',
'  - удары: 100% урона.',
'- **«безлимит», «бесконечно», «максимум», «миллион»** дают 999 999 ресурса.',
'- **Единственный лимит**: 200 военных на одного игрока. Большой призыв выходит из казарм потоком за пару секунд.',
'- **Нельзя**: то, чего нет в игре (криперы, драконы, машины, «заспавни меня в центре карты»), кикнуть, забанить или выбить игрока из раунда, выиграть раунд сразу, выдать донат (VIP, ADMIN, тикеты, робуксы). Такая команда отклоняется с причиной.',
'- База от панели не падает ниже 1 HP: добить её должна армия. Телепорт к чужой базе ставит армию рядом, а не на неё.',
'- **Всё действует только до конца раунда.**',
'- **Кому**:',
'  - «мне / мой / me / my»: автор команды; в дописке после рулетки «мне» означает того, кто дописал;',
'  - «врагам / enemies»: все, кроме себя;',
'  - «всем / everyone»: вообще все, включая тебя;',
'  - «всех» без уточнения в атакующей команде: враги;',
'  - «кроме меня / except me»: все, кроме себя;',
'  - можно просто написать ник игрока.',
'- **Числа** пиши как угодно: «100», «сто», «на 30 секунд», «на минуту», «50%», «в 5 раз», «x10».',
'- **Дописки после рулетки**: «x2», «в половину силы», «на 5 секунд», «но по автору», «отмена», или новая команда («и мне дай 50 лучников»). Если одна дописка не подходит, отклоняется только она.',
'- **Решётки**: все видят текст после фильтра Roblox, но команда выполняется по тому, что было набрано.','',
'Команды можно соединять: «дай мне 1000 золота и 500 дерева», «заморозь врагов и метеоры на Bob». Регистр букв не важен.','']
cats=[]
for c,_,_,_ in rows:
    if c not in cats: cats.append(c)
for c in cats:
    out+=['## '+c,'','| Русский | English |','|---|---|']
    for cc,_,ru,en in rows:
        if cc==c: out.append(f'| {ru} | {en} |')
    out.append('')
out+=[f'Всего в списке: {len(rows)} команд на каждом языке ({len(rows)*2} вместе). Каждая из них проверяется автотестом `tools/tests/cmdlist.lua`: она должна распознаваться мгновенно и выполняться в раунде.','',
'Bob и Carl в примерах — это ники других игроков: подставляй настоящие.','']
open(out_path,'w',encoding='utf-8').write('\n'.join(out))
print(len(rows))
